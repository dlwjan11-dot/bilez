export function initTypescale() {
    const base = document.getElementById('ts-base');
    const scale = document.getElementById('ts-scale');
    const font = document.getElementById('ts-font');
    const mode = document.getElementById('ts-mode');
    const preview = document.getElementById('ts-preview');
    const code = document.getElementById('ts-css');
    const copyTokensBtn = document.getElementById('ts-copy-tokens');
    const copyCssBtn = document.getElementById('ts-copy-css');

    if(!base || !preview) return; // Guard clause

    let currentScaleData = { tokens: {}, fontFamily: 'Inter' };
    
    // Listen for changes on all inputs (mode regenerates in its own change handler,
    // after it has swapped the 16/64 default)
    [base, scale, font].forEach(el => {
        if(el) el.addEventListener('input', generateTypeScale);
    });

    // Quality of life feature: When you switch to "Max", change 16px to 64px so it makes sense visually
    if(mode) {
        mode.addEventListener('change', (e) => {
            if(e.target.value === 'max' && base.value == 16) {
                base.value = 64;
            } else if (e.target.value === 'base' && base.value == 64) {
                base.value = 16;
            }
            generateTypeScale();
        });
    }

    function updateFontLink(fontName) {
         const id = 'ts-font-link';
         let link = document.getElementById(id);
         if(link) link.remove();
         
         link = document.createElement('link');
         link.id = id; 
         link.rel = 'stylesheet';
         link.href = `https://fonts.googleapis.com/css2?family=${fontName.replace(/ /g, '+')}:wght@400;700&display=swap`;
         document.head.appendChild(link);
    }

    function generateTypeScale() {
        const targetVal = parseFloat(base.value) || 16;
        const r = parseFloat(scale.value) || 1.25;
        const f = font.value || 'Inter';
        const calcMode = mode ? mode.value : 'base';

        let b = targetVal;
        if (calcMode === 'max') {
            b = targetVal / Math.pow(r, 5);
        }

        updateFontLink(f);
        preview.innerHTML = '';
        preview.style.fontFamily = `"${f}", sans-serif`;

        currentScaleData.fontFamily = f;
        currentScaleData.tokens = {};

        let css = `:root {\n  --font-base: ${b.toFixed(2)}px;\n  --font-family: '${f}', sans-serif;\n`;

        const steps = [5, 4, 3, 2, 1, 0, -1, -2];

        steps.forEach(i => {
            const size = (b * Math.pow(r, i)).toFixed(2);
            const rem = (size / 16).toFixed(3);

            const row = document.createElement('div');
            row.className = "border-b border-slate-100 pb-4 mb-4 flex flex-col sm:flex-row sm:items-baseline justify-between";

            const text = document.createElement('div');
            text.textContent = `A Visual Type Scale`;
            text.style.fontSize = `${size}px`;
            if(i > 0) text.style.fontWeight = "bold";

            const meta = document.createElement('div');
            meta.className = "text-xs text-slate-400 font-mono shrink-0 sm:ml-4 mt-2 sm:mt-0 text-right";

            let label = "";
            if (i === 5) label = `<span class="text-[9px] font-bold text-blue-500 uppercase block">Max (xl-5)</span>`;
            if (i === 0) label = `<span class="text-[9px] font-bold text-green-500 uppercase block">Base</span>`;

            meta.innerHTML = `${label}${size}px / ${rem}rem`;

            row.appendChild(text);
            row.appendChild(meta);
            preview.appendChild(row);

            let stepName = i > 0 ? `xl-${i}` : `sm-${Math.abs(i)}`;
            if (i === 0) stepName = 'base';

            css += `  --text-${stepName}: ${size}px;\n`;
            currentScaleData.tokens[`text-${stepName}`] = { '$value': `${size}px`, '$type': 'dimension' };
        });

        css += `}`;
        code.textContent = css;
    }

    if (copyCssBtn) {
        copyCssBtn.addEventListener('click', () => {
            navigator.clipboard.writeText(code.textContent);
            copyCssBtn.textContent = 'Copied!';
            setTimeout(() => copyCssBtn.textContent = 'Copy CSS', 1500);
        });
    }

    if (copyTokensBtn) {
        copyTokensBtn.addEventListener('click', () => {
            const output = {
                '$description': 'Type scale generated by Abdul Tools',
                'font-family': { '$value': `"${currentScaleData.fontFamily}", sans-serif`, '$type': 'fontFamily' },
                ...currentScaleData.tokens,
            };
            navigator.clipboard.writeText(JSON.stringify(output, null, 2));
            copyTokensBtn.textContent = 'Copied!';
            setTimeout(() => copyTokensBtn.textContent = 'Copy as W3C Design Tokens', 1500);
        });
    }
    
    // Call immediately to render the default view
    generateTypeScale();
}